def load_corpus(path=None):
    """학습용 한국어 말뭉치를 문자열로 돌려줍니다.

    path 를 주면 그 파일을 읽고, 없으면 내장된 작은 말뭉치를 씁니다.
    내장 말뭉치는 개념 확인용이라 아주 작습니다. 진짜 실험을 하려면
    한국어 위키 덤프 같은 큰 텍스트를 파일로 저장해 path 로 넘기세요.
    """
    if path and os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            return f.read()
    return _CORPUS.strip()


def load_sentences(path=None):
    """말뭉치를 문장(줄) 리스트로 돌려줍니다."""
    return [line.strip() for line in load_corpus(path).splitlines() if line.strip()]
